#!/usr/bin/env bash
# sync-contracts.sh <sha>
# Vendors the generated TypeScript from the public contracts repo at <sha> into
# src/contracts/tank and records the sha in src/contracts/VERSION. Never edit
# src/contracts/tank by hand: rerun this script with a newer sha instead.
set -euo pipefail

sha=${1:?usage: scripts/sync-contracts.sh <contracts-sha>}
repo=${CONTRACTS_REPO:-https://github.com/tactical-agent-neural-knowledge/contracts.git}
here=$(cd "$(dirname "$0")/.." && pwd)
dest="$here/src/contracts"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

echo "→ fetching contracts @ ${sha:0:12}"
git init -q "$tmp/contracts"
git -C "$tmp/contracts" remote add origin "$repo"
git -C "$tmp/contracts" fetch -q --depth 1 origin "$sha"
git -C "$tmp/contracts" checkout -q FETCH_HEAD

src="$tmp/contracts/gen/ts/src/tank"
[ -d "$src" ] || { echo "gen/ts/src/tank missing at $sha; run 'make gen' in contracts first"; exit 1; }

rm -rf "$dest/tank"
mkdir -p "$dest"
cp -R "$src" "$dest/tank"
printf '%s\n' "$sha" > "$dest/VERSION"

# One flat shim per package so consumers can import
# "@tactical-agent-neural-knowledge/sdk/contracts/<pkg>" without knowing the
# generated path. The namespaced barrel (index.ts) is hand-maintained.
for dir in "$dest"/tank/*/v1; do
  pkg=$(basename "$(dirname "$dir")")
  {
    echo "// Generated by scripts/sync-contracts.sh — do not edit."
    echo "export * from \"./tank/$pkg/v1/${pkg}_pb.js\";"
  } > "$dest/$pkg.ts"
done

echo "✓ src/contracts synced to $sha ($(find "$dest/tank" -name '*_pb.ts' | wc -l | tr -d ' ') files)"
